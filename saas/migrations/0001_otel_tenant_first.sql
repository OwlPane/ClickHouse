CREATE MATERIALIZED VIEW IF NOT EXISTS stumpcam.otel_traces_trace_id_ts_mv TO stumpcam.otel_traces_trace_id_ts
AS SELECT
    TenantId,
    TraceId,
    min(Timestamp) AS Start,
    max(Timestamp) AS End
FROM stumpcam.otel_traces
WHERE TraceId != ''
GROUP BY TenantId, TraceId;
